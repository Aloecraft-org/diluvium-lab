#!/usr/bin/env node
//
// Bundle notebooks/ into a module the page can open without a fetch.
//
//   node scripts/bundle-examples.mjs [--check]
//
// The examples are the onboarding path, so they have to work in every case
// the Lab works in -- including the baked single-file build, which has no
// `notebooks/` directory to fetch from, and a page opened with no network.
// Fetching them would make **Start here** the one button that breaks in
// exactly the situation someone reaches for it.
//
// So they are compiled into `src/notebook/examples.js` and committed. The
// same pattern as `vendor/pinned.js`: generated, checked in, and verified
// by `npm run release` rather than rebuilt at load. The `.ipynb` files stay
// the source of truth -- they are what you edit, what the tests run, and
// what someone downloads from the repository.
//
// `--check` reports drift instead of writing, which is what CI wants.

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'src/notebook/examples.js');

/**
 * The gallery's order, which is a decision rather than a filename sort.
 * `hello` first because it is the one that assumes nothing; the rest run
 * from the language outward to the things built on it.
 */
const ORDER = [
  'hello.ipynb',
  'language.ipynb',
  'secure-functions.ipynb',
  'messaging.ipynb',
  'sandbox.ipynb',
  'showing-things.ipynb',
  'sql.ipynb',
  'browser-check.ipynb',
];

async function build() {
  const present = (await readdir(resolve(ROOT, 'notebooks'))).filter((f) => f.endsWith('.ipynb'));
  const missing = ORDER.filter((f) => !present.includes(f));
  if (missing.length) throw new Error(`listed in ORDER but not in notebooks/: ${missing.join(', ')}`);
  // Unlisted files are an error rather than a silent omission: a notebook
  // nobody can reach is the same failure as a stale tag list, and this is
  // the only place that would notice.
  const unlisted = present.filter((f) => !ORDER.includes(f));
  if (unlisted.length) {
    throw new Error(`in notebooks/ but not listed in ORDER, so unreachable: ${unlisted.join(', ')}`);
  }

  const entries = [];
  for (const file of ORDER) {
    const text = await readFile(resolve(ROOT, 'notebooks', file), 'utf8');
    const doc = JSON.parse(text);                       // parse to fail loudly on a broken one
    const cells = doc.cells?.length ?? 0;
    if (!cells) throw new Error(`${file} has no cells`);
    entries.push({
      file,
      id: file.replace(/\.ipynb$/, ''),
      title: doc.metadata?.title ?? file,
      summary: doc.metadata?.diluvium_lab?.summary ?? '',
      cells,
      // Stored as a string, parsed on open. A notebook is a document, not
      // a value this module has an opinion about, and keeping it as text
      // means it round-trips byte-for-byte with the file on disk.
      source: text,
    });
  }

  const body = entries.map((e) => `  {
    id: ${JSON.stringify(e.id)},
    file: ${JSON.stringify(e.file)},
    title: ${JSON.stringify(e.title)},
    summary: ${JSON.stringify(e.summary)},
    cells: ${e.cells},
    source: ${JSON.stringify(e.source)},
  },`).join('\n');

  return `// Generated by scripts/bundle-examples.mjs. Do not edit.
//
// The example notebooks, compiled in so **Start here** works with no
// network and in the baked single-file build -- which has no notebooks/
// directory to fetch from. Edit the .ipynb files and re-run the script.

/** @type {Array<{id: string, file: string, title: string, summary: string, cells: number, source: string}>} */
export const EXAMPLES = [
${body}
];

/** One example by id, or null. */
export function exampleById(id) {
  return EXAMPLES.find((e) => e.id === id) ?? null;
}
`;
}

const wanted = await build();
if (process.argv.includes('--check')) {
  const have = await readFile(OUT, 'utf8').catch(() => '');
  if (have !== wanted) {
    console.error('bundle-examples: src/notebook/examples.js is out of date.');
    console.error('  a notebook changed without the bundle being rebuilt. Run:');
    console.error('    node scripts/bundle-examples.mjs');
    process.exit(1);
  }
  const count = (wanted.match(/^    id: /gm) ?? []).length;
  console.log(`bundle-examples: ${count} notebooks, up to date`);
} else {
  await writeFile(OUT, wanted);
  const count = (wanted.match(/^    id: /gm) ?? []).length;
  console.log(`bundle-examples: wrote src/notebook/examples.js (${count} notebooks, ${(wanted.length / 1024).toFixed(0)} KB)`);
}
